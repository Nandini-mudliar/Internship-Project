import requests
from IPython.display import display, Markdown
print('Ready to check messages.')

API_URL = 'https://ots.telecomsxchange.com/predict/'

def check_message(message):
    message = message.strip()
    if not message:
        print('Please enter a message first.')
        return
    if len(message) > 512:
        print('Please keep the message to 512 characters or fewer.')
        return

    payload = {'text': message, 'model': 'ots-mbert'}
    try:
        response = requests.post(API_URL, json=payload, timeout=30)
        response.raise_for_status()
        result = response.json()

        # The API returns a verdict label and a probability from 0 to 1.
        label = str(result.get('label', result.get('prediction', result.get('verdict', 'unknown')))).lower()
        probability = result.get('probability', result.get('confidence'))

        print('\nMessage checked:', message)
        if label == 'ham':
            print('RESULT: NOT SPAM (HAM)')
        elif label == 'spam':
            print('RESULT: SPAM')
        elif label == 'phishing':
            print('RESULT: PHISHING / POTENTIALLY DANGEROUS')
        else:
            print('API result:', result)

        if probability is not None:
            try:
                print('API confidence: {:.2f}%'.format(float(probability) * 100))
            except (TypeError, ValueError):
                print('API confidence:', probability)
        if result.get('processing_time') is not None:
            print('Server processing time:', result['processing_time'], 'seconds')
        print('\nNote: This is an automated estimate, not a guarantee that a message or link is safe.')
    except requests.exceptions.Timeout:
        print('The API took too long to respond. Please try again.')
    except requests.exceptions.RequestException as error:
        print('Could not contact the API. Check your internet connection and try again.')
        print('Technical detail:', error)
    except ValueError:
        print('The API returned a response that was not valid JSON.')

print('Function ready. Run the next cell to enter a message.')

user_message = input('Enter an SMS message to check: ')
check_message(user_message)